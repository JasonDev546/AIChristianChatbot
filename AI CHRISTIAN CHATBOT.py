class OpenAIClient:
    """Handles HTTP requests to the OpenAI API."""
    def __init__(self, api_key, model="gpt-3.5-turbo"):
        """Initialize the OpenAI client with the API key and the model to be used.
        """
        self.client = openai.OpenAI(api_key=api_key)  # Create an instance of the OpenAI client
        self.model = model  # Assign the selected model 

    def send_request(self, messages):
        """
        Sends a set of messages to the OpenAI API and
        returns the response.
        """
        try:

            # The API call is made to interact with the selected model
            response = self.client.chat.completions.create(
                model=self.model,  # Specifies the AI model to use
                messages=messages  # Sends the conversation history
            )

            # Extract the model's response from the API.
            reply = response.choices[0].message.content

            return reply  # Returns the response generated by the AI.

        except Exception as e:

            # Catch any errors that occur during the request to OpenAI.
            print(f"API Error: {e}")  # Shows error message.
            return f"Error: {e}"  # Returns error message.


class OpenAIChatbot:
    """
    This class uses OpenAIClient to send messages 
    and receive responses.
    """

    def __init__(self, api_key):
        """
        Initialize the chatbot with an OpenAI API client, and the variable representing 
        the history will be initialized as an empty list.
        """
        self.api_client = OpenAIClient(api_key)  # Creates an instance of the API client
        self.conversation_history = []  # Initializes the conversation history to maintain context

